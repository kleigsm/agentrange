"""把 results/batch-*.json 汇总成一张 Markdown 总表。

用法：.venv\\Scripts\\python.exe scripts\\summarize_results.py
输出：results/SUMMARY.md
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path("results")
OUT = RESULTS / "SUMMARY.md"


def fmt_ci(value: float, ci: list[float] | None) -> str:
    if ci and len(ci) == 2:
        return f"{value:.2f} [{ci[0]:.2f}, {ci[1]:.2f}]"
    return f"{value:.2f}"


def main() -> None:
    rows: list[dict] = []
    for path in sorted(RESULTS.glob("batch-*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        if "task" not in data or "asr" not in data:
            continue
        rows.append(
            {
                "task": data.get("task", "?"),
                "model": data.get("model", "?"),
                "defense": data.get("defense", "none"),
                "recovery": bool(data.get("recovery", False)),
                "trials": data.get("trials", 0),
                "asr": float(data.get("asr", 0.0)),
                "asr_ci": data.get("asr_ci95"),
                "violation": float(data.get("policy_violation_rate", 0.0)),
                "utility": float(data.get("utility", 0.0)),
                "file": path.name,
            }
        )

    rows.sort(key=lambda r: (r["task"], r["model"], r["defense"], r["recovery"]))

    lines = [
        "# Results summary",
        "",
        "Generated by `scripts/summarize_results.py`.",
        "",
        "| Task | Model | Defense | Recovery | n | ASR (95% CI) | Violation | Utility |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        defense = r["defense"].replace(",", " + ")
        lines.append(
            "| {task} | {model} | {defense} | {rec} | {n} | {asr} | {viol:.2f} | {util:.2f} |".format(
                task=r["task"],
                model=r["model"],
                defense=defense,
                rec="yes" if r["recovery"] else "no",
                n=r["trials"],
                asr=fmt_ci(r["asr"], r["asr_ci"]),
                viol=r["violation"],
                util=r["utility"],
            )
        )

    lines += [
        "",
        f"{len(rows)} batch results.",
        "",
        "> Different tasks have different difficulty and baselines;",
        "> compare ASR across defenses only within the same task and model.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
